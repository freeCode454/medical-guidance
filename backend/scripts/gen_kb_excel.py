def main() -> None:
    wb = Workbook()
    wb.remove(wb.active)

    # 说明 sheet 放最前
    ws = wb.create_sheet("说明")
    for row in README:
        ws.append(row)
    ws.column_dimensions["A"].width = 18
    ws.column_dimensions["B"].width = 70
    ws["A1"].font = TITLE_FONT

    for name, rows, headers in SHEETS:
        ws = wb.create_sheet(name)
        ws.append(headers)
        for cell in ws[1]:
            cell.fill = HEADER_FILL
            cell.font = HEADER_FONT
            cell.alignment = Alignment(vertical="center")
        for row in rows:
            ws.append(row)
        # 自适应列宽（按内容长度，上限 60）
        for i, h in enumerate(headers, start=1):
            max_len = len(h)
            for row in rows:
                if i <= len(row) and row[i - 1] is not None:
                    max_len = max(max_len, len(str(row[i - 1])))
            ws.column_dimensions[get_column_letter(i)].width = min(max_len + 4, 60)
        # 文本列自动换行
        for row in ws.iter_rows(min_row=2):
            for cell in row:
                cell.alignment = Alignment(vertical="top", wrap_text=True)
        ws.freeze_panes = "A2"

    out = Path(__file__).resolve().parent.parent.parent / "kb" / "医学知识库源数据.xlsx"
    out.parent.mkdir(parents=True, exist_ok=True)
    wb.save(out)
    print(f"已生成 {out}")
    for name, rows, _ in SHEETS:
        print(f"  {name}: {len(rows)} 条")


if __name__ == "__main__":
    main()
